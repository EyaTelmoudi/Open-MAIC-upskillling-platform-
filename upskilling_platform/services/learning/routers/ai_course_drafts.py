@router.post("/{draft_id}/save-platform-draft", response_model=dict)
def save_ai_course_as_platform_draft(
    draft_id: str,
    payload: dict,
    current_user: dict = Depends(get_current_user),
    db: Session = Depends(get_db),
):
    user = _get_user_from_payload(current_user, db)
    _require_course_edit_role(user)

    query = db.query(AICourseDraft).filter(AICourseDraft.external_draft_id == draft_id)
    if user.role != "SuperAdmin":
        query = query.filter(AICourseDraft.tenant_id == user.tenant_id)
    record = query.first()
    if not record:
        raise HTTPException(status_code=404, detail="AI course draft not found")

    course = _upsert_platform_course(db, record, user)
    record.review_status = "draft_saved"
    record.approved_by = payload.get("approvedBy") or user.email
    record.approved_at = datetime.utcnow()

    db.commit()
    db.refresh(record)
    db.refresh(course)

    return {
        "success": True,
        "record": _review_record(record),
        "platformCourseId": str(course.id),
    }
