@router.post("/sync", response_model=dict)
def sync_ai_course_draft(
    payload: dict,
    current_user: dict = Depends(get_current_user),
    db: Session = Depends(get_db),
):
    user = _get_user_from_payload(current_user, db)
    _require_course_edit_role(user)

    draft = payload.get("draft")
    if not isinstance(draft, dict):
        raise HTTPException(status_code=400, detail="Missing draft payload")

    draft_id = draft.get("draftId")
    if not draft_id:
        raise HTTPException(status_code=400, detail="Draft payload missing draftId")

    record = (
        db.query(AICourseDraft)
        .filter(AICourseDraft.external_draft_id == str(draft_id))
        .first()
    )
    if not record:
        record = AICourseDraft(
            external_draft_id=str(draft_id),
            author_id=user.id,
            tenant_id=user.tenant_id,
            created_at=datetime.utcnow(),
        )
        db.add(record)

    record.submission_id = draft.get("submissionId")
    record.classroom_id = draft.get("classroomId")
    record.title = _extract_title(draft)
    record.status = str(draft.get("status") or "draft")
    record.prompt = payload.get("prompt") or record.prompt
    record.source_pdf_name = payload.get("sourcePdfName") or record.source_pdf_name
    record.output_dir = draft.get("outputDir")
    record.output_dir_relative = draft.get("outputDirRelative")
    record.stage_data = draft.get("stage")
    record.draft_payload = draft
    record.author_id = user.id
    record.tenant_id = user.tenant_id

    final_course = payload.get("finalCourse")
    if isinstance(final_course, dict):
        record.final_course_payload = final_course
        record.final_course_path = payload.get("finalCoursePathRelative") or record.final_course_path

    if payload.get("reviewStatus"):
        record.review_status = str(payload["reviewStatus"])

    db.commit()
    db.refresh(record)
    return {
        "success": True,
        "draft": record.draft_payload,
        "summary": _draft_summary(record),
        "record": _review_record(record),
    }


