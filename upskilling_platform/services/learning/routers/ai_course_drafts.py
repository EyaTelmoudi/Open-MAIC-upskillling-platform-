"""Persistence router for AI-generated course drafts and final approvals."""

from __future__ import annotations

import json
from datetime import datetime

from fastapi import APIRouter, Depends, HTTPException, status
from sqlalchemy.orm import Session

from common.database import get_db
from common.models import AICourseDraft, Course, Lesson, Module, User
from services.learning.routers.courses import (
    _get_user_from_payload,
    _require_course_edit_role,
    get_current_user,
)

router = APIRouter(prefix="/ai-course-drafts", tags=["ai-course-drafts"])


def _extract_title(draft: dict) -> str:
    stage_name = draft.get("stage", {}).get("name")
    if stage_name:
        return str(stage_name)
    scenes = draft.get("editableScenes") or draft.get("sourceScenes") or []
    if scenes:
        return str(scenes[0].get("title") or "Generated course")
    return "Generated course"


def _draft_summary(record: AICourseDraft) -> dict:
    payload = record.draft_payload or {}
    editable_scenes = payload.get("editableScenes") or []
    approved_scenes = sum(1 for scene in editable_scenes if scene.get("status") == "approved")
    return {
        "draftId": record.external_draft_id,
        "submissionId": record.submission_id,
        "classroomId": record.classroom_id,
        "outputDirRelative": record.output_dir_relative,
        "title": record.title,
        "createdAt": record.created_at.isoformat(),
        "updatedAt": record.updated_at.isoformat(),
        "status": record.status,
        "scenesCount": len(editable_scenes),
        "approvedScenesCount": approved_scenes,
        "reviewStatus": record.review_status,
        "platformCourseId": str(record.platform_course_id) if record.platform_course_id else None,
    }


def _review_record(record: AICourseDraft) -> dict:
    return {
        "draftId": record.external_draft_id,
        "status": record.review_status,
        "approvedBy": record.approved_by,
        "approvedAt": record.approved_at.isoformat() if record.approved_at else None,
        "createdAt": record.created_at.isoformat(),
        "updatedAt": record.updated_at.isoformat(),
        "platformCourseId": str(record.platform_course_id) if record.platform_course_id else None,
    }


def _serialize_scene_for_lesson(scene: dict) -> str:
    return json.dumps(scene, ensure_ascii=True)


def _scene_duration(scene: dict) -> int:
    actions = scene.get("actions") or []
    speech_actions = [action for action in actions if action.get("type") == "speech"]
    if not speech_actions:
        return 5

    total_words = 0
    for action in speech_actions:
        text = str(action.get("text") or "")
        total_words += len(text.split())
    return max(5, min(30, (total_words // 40) + 1))


def _upsert_platform_course(
    db: Session,
    record: AICourseDraft,
    current_user: User,
) -> Course:
    final_course = record.final_course_payload
    if not final_course:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Finalize the AI course before saving it as a platform draft",
        )

    course = None
    if record.platform_course_id:
        course = db.query(Course).filter(Course.id == record.platform_course_id).first()

    course_title = str(final_course.get("stage", {}).get("name") or record.title)
    scenes = sorted(final_course.get("scenes") or [], key=lambda scene: scene.get("order", 0))
    estimated_duration = sum(_scene_duration(scene) for scene in scenes) or max(len(scenes) * 5, 5)

    if not course:
        course = Course(
            title=course_title,
            description=(
                "AI-generated course draft created from OpenMAIC and saved for learning-expert review."
            ),
            thumbnail=None,
            category="AI Generated",
            difficulty="Intermediate",
            duration=estimated_duration,
            xp_reward=100,
            is_published=False,
            author_id=current_user.id,
            tenant_id=current_user.tenant_id,
        )
        db.add(course)
        db.flush()
    else:
        course.title = course_title
        course.description = (
            "AI-generated course draft created from OpenMAIC and saved for learning-expert review."
        )
        course.duration = estimated_duration
        course.author_id = current_user.id
        course.tenant_id = current_user.tenant_id
        course.is_published = False

        for module in list(course.modules):
            for lesson in list(module.lessons):
                db.delete(lesson)
            db.delete(module)
        db.flush()

    module = Module(
        course_id=course.id,
        title="Generated Course Content",
        description="Lesson sequence generated by OpenMAIC and approved by the learning expert.",
        order=1,
    )
    db.add(module)
    db.flush()

    for index, scene in enumerate(scenes, start=1):
        lesson = Lesson(
            module_id=module.id,
            title=str(scene.get("title") or f"Scene {index}"),
            content=_serialize_scene_for_lesson(scene),
            video_url=None,
            content_type=str(scene.get("type") or "slide"),
            duration=_scene_duration(scene),
            order=index,
            assessment_id=None,
        )
        db.add(lesson)

    record.platform_course_id = course.id
    return course


@router.get("/", response_model=dict)
def list_ai_course_drafts(
    current_user: dict = Depends(get_current_user),
    db: Session = Depends(get_db),
):
    user = _get_user_from_payload(current_user, db)
    _require_course_edit_role(user)

    query = db.query(AICourseDraft)
    if user.role != "SuperAdmin":
        query = query.filter(AICourseDraft.tenant_id == user.tenant_id)

    drafts = query.order_by(AICourseDraft.updated_at.desc()).all()
    return {"success": True, "drafts": [_draft_summary(draft) for draft in drafts]}


@router.get("/by-platform-course/{course_id}", response_model=dict)
def get_ai_course_draft_by_platform_course(
    course_id: str,
    current_user: dict = Depends(get_current_user),
    db: Session = Depends(get_db),
):
    user = _get_user_from_payload(current_user, db)
    _require_course_edit_role(user)

    query = db.query(AICourseDraft).filter(AICourseDraft.platform_course_id == course_id)
    if user.role != "SuperAdmin":
        query = query.filter(AICourseDraft.tenant_id == user.tenant_id)

    record = query.order_by(AICourseDraft.updated_at.desc()).first()
    if not record:
        course = db.query(Course).filter(Course.id == course_id).first()
        if course:
            fallback_query = db.query(AICourseDraft).filter(AICourseDraft.title == course.title)
            if user.role != "SuperAdmin":
                fallback_query = fallback_query.filter(AICourseDraft.tenant_id == user.tenant_id)
            record = fallback_query.order_by(AICourseDraft.updated_at.desc()).first()

            if record and not record.platform_course_id:
                record.platform_course_id = course.id
                db.commit()
                db.refresh(record)

    if not record:
        raise HTTPException(status_code=404, detail="AI course draft not found for this platform course")

    return {
        "success": True,
        "draftId": record.external_draft_id,
        "record": _review_record(record),
    }


